D=$(cd "$(dirname "$0")" && pwd)
G=~/android-sdk/ndk/28.2.13676358/shader-tools/linux-x86_64/glslc
OUT=${1:-$D/frame_generation_shaders.inc}
echo "// Generated by glslc -O from the fg_*.comp sources (frame generation)." > $OUT
for s in luma match median interp copy; do
  $G -O -fshader-stage=compute -mfmt=num -o /tmp/fg_$s.num $D/fg_$s.comp || exit 1
  echo "const uint32_t kFg_$s[] = {" >> $OUT; cat /tmp/fg_$s.num >> $OUT; echo "};" >> $OUT
done
wc -c $OUT
