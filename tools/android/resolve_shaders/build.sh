# Builds the fused direct resolve shaders into a C header (run in WSL):
#   build.sh [output header]   (default: next to this script)
# direct_resolve_full_32bpp.comp is regenerated from the SDK's resolve_full_32bpp copy shader.
set -e
G=~/android-sdk/ndk/28.2.13676358/shader-tools/linux-x86_64/glslc
D=$(cd "$(dirname "$0")" && pwd)
O=${1:-$D/direct_resolve_shaders.h}
SDK=${SDK:-$(cd "$(dirname "${BASH_SOURCE[0]}")/../../.." && pwd)/../rexglue-sdk-android}
python3 "$D/make_fused_full.py" "$SDK/src/graphics/shaders/vulkan_spirv/resolve_full_32bpp_cs.h" \
  "$D/direct_resolve_full_32bpp.comp"
T=$(mktemp -d)
echo "// Generated by tools/android/resolve_shaders/build.sh." > "$O"
for kind in fast full 8888; do
  for m in 0 1; do
    "$G" -O --target-env=vulkan1.0 -fshader-stage=compute -DMSAA=$m \
      "$D/direct_resolve_${kind}$( [ $kind = 8888 ] || echo _32bpp).comp" -o "$T/dr.spv"
    echo "const uint32_t direct_resolve_${kind}$( [ $kind = 8888 ] || echo _32bpp)_msaa${m}_cs[] = {" >> "$O"
    python3 "$D/spv_to_c.py" "$T/dr.spv" >> "$O"
    echo "};" >> "$O"
  done
done
for m in 0 1; do
  "$G" -O --target-env=vulkan1.0 -fshader-stage=compute -DMSAA=$m -DDEPTH=1 \
    "$D/direct_resolve_fast_32bpp.comp" -o "$T/dr.spv"
  echo "const uint32_t direct_resolve_fast_depth_msaa${m}_cs[] = {" >> "$O"
  python3 "$D/spv_to_c.py" "$T/dr.spv" >> "$O"
  echo "};" >> "$O"
done
rm -rf "$T"
wc -c "$O"
