# Makes direct_resolve_full_32bpp.comp from the SDK's resolve_full_32bpp copy shader: the shader
# is decompiled with spirv-cross (Ubuntu package), its EDRAM buffer loads are replaced with loads
# from the host render target (packed the way the EDRAM dump packs 8_8_8_8), and the bindings are
# changed to the direct resolve pipeline layout (set 0 destination, set 1 render target).
#   python3 make_fused_full.py <sdk>/src/graphics/shaders/vulkan_spirv/resolve_full_32bpp_cs.h out.comp
import re
import struct
import subprocess
import sys
import tempfile

header, out_path = sys.argv[1], sys.argv[2]
text = open(header).read()
body = text[text.index('{') + 1:text.rindex('}')]
words = [int(x, 16) for x in re.findall(r'0x[0-9A-Fa-f]+', body)]
with tempfile.NamedTemporaryFile(suffix='.spv', delete=False) as f:
    f.write(struct.pack('<%dI' % len(words), *words))
    spv = f.name
glsl = subprocess.check_output(['spirv-cross', '--vulkan-semantics', spv], text=True)

old_bindings = re.search(r'layout\(set = 0, binding = 0, std430\) readonly buffer.*?\} _3305;\n',
                         glsl, re.S)
assert old_bindings, 'unexpected decompiled layout'
new_bindings = """#extension GL_EXT_samplerless_texture_functions : require
layout(set = 0, binding = 0, std430) writeonly buffer XeResolveDest
{
    uvec4 _m0[];
} _5522;

#if MSAA
layout(set = 1, binding = 0) uniform texture2DMS xe_source;
#else
layout(set = 1, binding = 0) uniform texture2D xe_source;
#endif

layout(push_constant, std430) uniform XeDirectResolveConstants
{
    uint _m0;  // edram_info
    uint _m1;  // coordinate_info
    uint _m2;  // dest_info
    uint _m3;  // dest_coordinate_info
    uint _m4;  // dest_base
    uint _m5;  // render target EDRAM base tile
    uint _m6;  // render target pitch in tiles
    uint _m7;  // host sample index of guest sample 0 (bits 0:1) and 1 (bits 2:3)
} _3305;

// The 32-bit EDRAM sample at a sample address: the render target sample that the EDRAM dump
// would have stored there (32bpp tiles are 80x16 samples; 2x MSAA samples are stacked rows).
// The samples one invocation reads mostly lie in one tile: its origin in the render target is
// computed once (the division by the render target pitch is the expensive part).
uint xe_memo_tile = 0xFFFFFFFFu;
uvec2 xe_memo_tile_origin = uvec2(0u);
uint LoadEdramSample(uint address)
{
    uint tile = address / 1280u;
    if (tile != xe_memo_tile)
    {
        xe_memo_tile = tile;
        uint source_tile = (tile + 2048u - _3305._m5) & 2047u;
        uint source_tile_y = source_tile / _3305._m6;
        xe_memo_tile_origin =
            uvec2((source_tile - source_tile_y * _3305._m6) * 80u, source_tile_y * 16u);
    }
    uint tile_sample = address - tile * 1280u;
    uint tile_sample_y = tile_sample / 80u;
    uint tile_sample_x = tile_sample - tile_sample_y * 80u;
    uint sample_x = xe_memo_tile_origin.x + tile_sample_x;
    uint sample_y = xe_memo_tile_origin.y + tile_sample_y;
#if MSAA
    ivec2 pixel = ivec2(uvec2(sample_x, sample_y >> 1u));
    if (any(greaterThanEqual(pixel, textureSize(xe_source))))
    {
        return 0u;
    }
    int sample_id = int((_3305._m7 >> ((sample_y & 1u) << 1u)) & 3u);
    vec4 color = texelFetch(xe_source, pixel, sample_id);
#else
    ivec2 pixel = ivec2(uvec2(sample_x, sample_y));
    if (any(greaterThanEqual(pixel, textureSize(xe_source, 0))))
    {
        return 0u;
    }
    vec4 color = texelFetch(xe_source, pixel, 0);
#endif
    uvec4 unorm = uvec4(color * 255.0 + 0.5);
    return (unorm.x & 255u) | ((unorm.y & 255u) << 8u) | ((unorm.z & 255u) << 16u) | (unorm.w << 24u);
}
"""
glsl = glsl[:old_bindings.start()] + new_bindings + glsl[old_bindings.end():]
glsl, loads = re.subn(r'_3271\._m0\[([^\]]*)\]', r'LoadEdramSample(\1)', glsl)
assert '_3271' not in glsl, 'unreplaced EDRAM access'
banner = ("// Generated by tools/android/resolve_shaders/make_fused_full.py from the SDK's\n"
          "// resolve_full_32bpp copy shader (decompiled; %d EDRAM loads redirected to the render target).\n"
          % loads)
lines = glsl.split('\n', 1)
open(out_path, 'w').write(lines[0] + '\n' + banner + lines[1])
print(loads, 'loads replaced')
